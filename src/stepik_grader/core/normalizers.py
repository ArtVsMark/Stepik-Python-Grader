"""normalizers.py — утилиты нормализации вывода для сравнения тест-кейсов.

Используется grader_core.py: ``normalize_floats`` импортируется как
``_normalize_output_line`` и применяется построчно при сравнении фактического
вывода решения с ожидаемым (см. ``grader_core.run_single_test``).

``sort_lines`` и ``normalize_whitespace`` — experimental: полностью
реализованы и покрыты тестами, но пока не подключены ни к одному режиму
grader_core.py (нет UI-опции "сравнивать вывод без учёта порядка строк" /
"игнорировать лишние пробелы"). Сохранены как готовый строительный блок для
такой опции (Issue #21 finding, Sprint 6.2).
"""

from __future__ import annotations

import math
import re
from decimal import Decimal, InvalidOperation

__all__ = [
    "floats_equal_with_precision",
    "normalize_floats",
    "normalize_whitespace",
    "sort_lines",
    "split_output_lines",
    "strip_trailing_blanks",
]

# issue #843: ``str.splitlines()`` считает переводом строки ещё восемь символов
# сверх ``\n`` — VT, FF, FS/GS/RS, NEL и U+2028/U+2029. Для сравнения вывода это
# ложное совпадение: строка ``a<VT>b`` распадалась на две и признавалась равной
# ожиданию из двух НАСТОЯЩИХ строк, то есть неверное решение получало AC.
# Разделителями считаем ровно то, что ими является в файлах и в потоках:
# ``\r\n``, одиночный ``\r`` (universal newlines — так же читает файлы
# ``Path.read_text``) и ``\n``.
_LINE_BREAK_RE = re.compile(r"\r\n|\r|\n")


def split_output_lines(text: str) -> list[str]:
    """Разбить текст на строки только по настоящим переводам строки (issue #843).

    Отличие от ``str.splitlines()`` — ровно в наборе разделителей: прочие
    управляющие символы остаются ДАННЫМИ внутри строки. Завершающий перевод
    строки, как и у ``splitlines``, лишней пустой строки не создаёт.

    Примеры:
        ``"a\\nb\\n"``    → ``["a", "b"]``
        ``"a\\r\\nb"``     → ``["a", "b"]``   (Windows-поток)
        ``"a\\x0bb"``     → ``["a\\x0bb"]``   (splitlines дал бы два элемента)
        ``""``           → ``[]``
    """
    if not text:
        return []
    lines = _LINE_BREAK_RE.split(text)
    if lines[-1] == "":
        lines.pop()
    return lines


#: Что снимается с конца строки в режиме ``stepik``: обычный пробел и
#: табуляция, и ничего больше. Голый ``str.rstrip()`` здесь **нельзя**: он
#: считает пробельными ещё и ``\x0b``/``\x0c``, а по #843 они — ДАННЫЕ внутри
#: строки, а не разделители. С ``rstrip()`` мутация ``vertical_tab`` из каталога
#: корпуса начала получать AC — ровно тот ложный AC, который #843 и закрывал.
_TRAILING_BLANKS = " \t"


def strip_trailing_blanks(lines: list[str]) -> list[str]:
    """Убрать хвостовые пробелы каждой строки и пустые строки в конце (issue #1111).

    Нормализация режима сравнения ``stepik``: ровно то, что не различает чекер
    платформы, и ничего сверх. Ведущие и внутренние пробелы, порядок строк,
    регистр и число содержательных строк остаются значимыми — ни один из
    закрытых ложных AC (#843, #940, #1031) этим не возвращается.

    Снимаются только пробел и табуляция. Вертикальная табуляция, перевод
    страницы и неразрывный пробел — данные: `a<VT>` и `a` остаются разными
    выводами.

    Зачем понадобилось: на реальной базе курса решения, **принятые Stepik**,
    получали у нас ``WA`` — расхождение было в хвостовом пробеле (`print(x,
    end=' ')`) и в «ноль строк против одной пустой». Побайтовая сверка живёт в
    режиме ``strict``.

    Примеры:
        ``["a ", "b\\t"]``   → ``["a", "b"]``
        ``["a", "", ""]``    → ``["a"]``
        ``[""]``             → ``[]``
        ``["", "a"]``        → ``["", "a"]``   (пустая строка В НАЧАЛЕ значима)
        ``["a\\x0b"]``        → ``["a\\x0b"]``   (VT — данные, issue #843)
    """
    trimmed = [line.rstrip(_TRAILING_BLANKS) for line in lines]
    while trimmed and not trimmed[-1]:
        trimmed.pop()
    return trimmed


# issue #410 (B5): lookbehind/lookahead не дают матчить float ВНУТРИ версии/
# dotted-числа (`3.10.5` иначе → `3.1.5`, а IP `1.2.3.4` — покорёжился бы):
# `(?<![\d.])` — не начинать после цифры/точки (середина версии),
# `(?!\.\d)` — не заканчивать перед `.цифра` (за числом следует ещё сегмент).
# Обычные float'ы (`3.14`, `-0.5`, `1.5e10`, `3.14.` в конце предложения) не
# затронуты — защищены только dotted-последовательности.
_FLOAT_RE = re.compile(r"(?<![\d.])-?\d+\.\d+(?:[eE][+-]?\d+)?(?!\.\d)")


def normalize_floats(text: str) -> str:
    """Нормализует числа с плавающей точкой, округляя до 9 знаков.

    Применяет ``str(round(float(x), 9))`` к каждому совпадению регулярного
    выражения, построчно. Для очень малых значений это даёт научную нотацию
    (``0.0000001`` → ``1e-07``) — поведение совпадает с прежней inline-функцией
    grader._normalize_output_line, которая является источником истины.

    Примеры:
        '5.000000000000001' → '5.0'
        '3.14159265358979'  → '3.141592654'
        '0.0000001'         → '1e-07'
    """

    def _round_float(m: re.Match[str]) -> str:
        try:
            return str(round(float(m.group()), 9))
        # issue #405: ветка защитная и недостижима реальным входом — _FLOAT_RE
        # матчит только валидный float-синтаксис, а overflow float() даёт inf,
        # не ValueError. Оставлена на случай будущих правок regex.
        except ValueError:  # pragma: no cover
            return m.group()

    return "\n".join(_FLOAT_RE.sub(_round_float, line) for line in text.split("\n"))


def _decimal_digits(number: str) -> int:
    """Сколько знаков после запятой в десятичной записи числа.

    Экспоненциальная запись (``1e-07``) даёт 0: разрядность там не выражена и
    требованием формата быть не может.
    """
    if "e" in number or "E" in number:
        return 0
    _, _, frac = number.partition(".")
    return len(frac)


#: Значащих цифр, которые ещё различает double. Запись длиннее этого предела
#: округляется при `float()` — и два РАЗНЫХ числа становятся одним.
_DOUBLE_SIGNIFICANT_DIGITS = 17


def _significant_digits(number: str) -> int:
    """Сколько значащих цифр в записи числа (нули слева и знак не считаются)."""
    digits = number.lstrip("-+").replace(".", "").lstrip("0")
    return len(digits)


def _beyond_double(number: str) -> bool:
    """Теряет ли запись информацию при переводе во ``float`` (issue #996).

    Два случая, и оба означают, что ``round(float(x), 9)`` сравнивать уже
    нечего — исходные числа до него не доживают:

    * **переполнение** — ``1.0e400`` даёт ``inf``, и любое другое переполнение
      даёт тот же ``inf`` (``PY-1-02``);
    * **больше значащих цифр, чем держит double** — ``123456789012345678.0`` и
      ``…679.0`` получают один repr (``MTX-8-02``).

    Оба — не следствие контракта «сравниваем до девяти знаков», а следствие
    ограничений двоичного представления. Поэтому здесь толерантность неуместна:
    числа сравниваются точно.
    """
    if _significant_digits(number) > _DOUBLE_SIGNIFICANT_DIGITS:
        return True
    try:
        return not math.isfinite(float(number))
    except (ValueError, OverflowError):  # pragma: no cover — regex даёт валидный синтаксис
        return True


def _distinguishable_by_value(actual: str, expected: str) -> bool:
    """Разные ли это числа там, где ``float`` их уже не различает (issue #996).

    ``normalize_floats`` округляет до девяти знаков, и это осознанный контракт
    сравнения: «до девяти знаков после запятой» — обычное требование задачи, а
    двоичный шум (``0.30000000000000004`` против ``0.3``) обязан считаться
    совпадением, иначе грейдер бесполезен на дробях (issue #940).

    Но там, где число **не доживает** до округления, контракт ни при чём:
    ``1.0e400`` превращается в ``inf`` наравне с любым другим переполнением, а
    восемнадцатизначное целое теряет последнюю цифру. Такие пары сравниваются
    точно, через ``Decimal`` — он не переполняется и держит все цифры записи.

    Что осталось **намеренно** склеенным: числа меньше 5e-10. ``0.0000000002``
    по-прежнему принимается за ``0.0000000001``, потому что оба укладываются в
    девять знаков после запятой; сузить это — значит завернуть законное
    ``print(0.1234567894)`` при ожидании ``0.123456789``. Находки ``MTX-8-01`` и
    ``MTX-8-03`` в этой части отклонены: они описывают сам контракт, а не
    отступление от него.

    ``True`` означает «это разные числа, вердикт не должен их путать».
    """
    if not (_beyond_double(actual) or _beyond_double(expected)):
        return False
    try:
        return Decimal(actual) != Decimal(expected)
    except InvalidOperation:  # pragma: no cover — _FLOAT_RE даёт валидный синтаксис
        return False


def floats_equal_with_precision(actual: str, expected: str) -> bool:
    """Сравнить строки с float-толерантностью, не теряя требования разрядности.

    issue #940: толерантность к записи float нужна — ``0.30000000000000004``
    против ``0.3`` обязано быть ``AC``, иначе двоичное представление делает
    грейдер бесполезным. Но она же стирала **незначащие нули**: ожидание
    ``12.30`` и вывод ``12.3`` после ``round(..., 9)`` превращались в одну
    строку, и задача «вывести с точностью до сотых» принимала решение, которое
    её требование не выполняет. Направление вреда худшее из возможных —
    грейдер зеленее платформы: локальный ``AC``, ``WA`` на Stepik.

    Поэтому толерантность сохраняется, но не там, где ожидание требует **больше**
    знаков, чем напечатало решение. Если число float-совпадений в строках
    различается, проверка разрядности пропускается: это случай разных форм
    записи (``1e-07`` против ``0.0000001``), где сравнивать знаки нечего.

    issue #996: округление до девяти знаков **абсолютное**, поэтому там, где
    double не решает, оно склеивало РАЗНЫЕ числа и выдавало ложный ``AC``.
    Три таких случая (все воспроизведены на этом пути) проверяются точно, до
    округления, — см. :func:`_distinguishable_by_value`.
    """
    if normalize_floats(actual) != normalize_floats(expected):
        return False
    actual_numbers = _FLOAT_RE.findall(actual)
    expected_numbers = _FLOAT_RE.findall(expected)
    if len(actual_numbers) != len(expected_numbers):
        return True
    if any(
        _distinguishable_by_value(a, e)
        for a, e in zip(actual_numbers, expected_numbers, strict=True)
    ):
        return False
    return all(
        _decimal_digits(a) >= _decimal_digits(e)
        for a, e in zip(actual_numbers, expected_numbers, strict=True)
    )


def sort_lines(output: str) -> str:
    """Сортирует строки вывода (для задач где порядок строк не важен).

    Experimental: не вызывается из grader_core.py — см. docstring модуля.
    """
    return "\n".join(sorted(output.strip().splitlines()))


def normalize_whitespace(output: str) -> str:
    """Нормализует пробелы: strip + схлопывает множественные пробелы.

    Experimental: не вызывается из grader_core.py — см. docstring модуля.
    """
    return "\n".join(" ".join(line.split()) for line in output.splitlines())
