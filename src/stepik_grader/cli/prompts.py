"""cli/prompts.py — наборы утвердительных ответов на вопросы CLI (issue #899).

Архитектурный слой: Application / CLI (leaf — не импортирует ничего из проекта).

Наборов ДВА, и разница между ними смысловая, а не случайная:

* :data:`CONFIRM_YES` — согласие с ПРЕДЛОЖЕННЫМ действием («проверить скачанную
  задачу сейчас?»). Пустой Enter здесь означает «да»: это подсказанный следующий
  шаг, и заставлять набирать букву — лишний барьер ровно там, где мы экономим
  ввод.
* :data:`EXPLICIT_YES` — ЯВНОЕ согласие на действие с внешними последствиями
  (отправка кода решения и его ввода-вывода AI-провайдеру). Пустой Enter здесь
  означает «нет»: молчание согласием не является, и умолчание обязано быть
  безопасным.

Раньше оба набора жили безымянными литералами в ``commands.py`` и
``interactive.py`` и выглядели как копипаста с опечаткой. Следующий, кто решил бы
«привести к одному виду», молча превратил бы запрос согласия в «Enter = да» —
то есть сломал бы приватный контракт, не тронув ни одного теста. Имена и этот
докстринг существуют, чтобы такого соблазна не возникало.
"""

from __future__ import annotations

__all__ = ["CONFIRM_YES", "EXPLICIT_YES"]

# Ответы, означающие «да». Латиница и кириллица: раскладку под вопрос никто не
# переключает, и «lf» вместо «да» — самая частая опечатка в русском интерфейсе.
_YES_WORDS = frozenset({"y", "yes", "д", "да"})

#: Согласие с предложенным действием; пустой ввод — «да».
CONFIRM_YES = _YES_WORDS | {""}

#: Явное согласие на отправку данных наружу; пустой ввод — «нет».
EXPLICIT_YES = _YES_WORDS
