"""task_scaffold.py — каталог задачи без Stepik (issue #1072, находка STR-3-05).

Архитектурный слой: Domain (leaf — только stdlib, не импортирует project-код).

Каталог задачи умел создавать один загрузчик, то есть чтобы просто попробовать
грейдер на своей задаче, человеку нужны были аккаунт Stepik, OAuth-приложение и
сеть. Формат при этом открытый и описан как контракт
([`docs/use/configuration.md` § Каталог задачи без Stepik](../../../docs/use/configuration.md)) —
загрузчик его лишь заполняет.

Здесь та же раскладка делается локально:

```text
<ИМЯ>/
├── task1_1.py        # решение
└── tests/
    ├── 1             # вход теста №1
    └── 1.clue        # ожидаемый вывод теста №1
```

**Шаблон решения рабочий, а не пустой.** Приёмка задачи требует, чтобы
созданный каталог проходил ``--mode 1`` без единой правки, а пустой файл этого
не делает: первое, что увидел бы человек, — красный прогон на том, что ему
только что создали. Поэтому внутри минимальное работающее решение, и оно же
служит подсказкой: видно, откуда берётся вход и куда идёт ответ.

**`meta.json` не создаётся.** Файл опционален, и пустой только сбивает с толку:
читатель начинает искать, что там должно быть. Для function-style задачи
достаточно одной строки, и её называет вывод команды.

**Существующий каталог не перезатирается** — как у ``--init-vscode``. Молча
затёртая чужая работа дороже любого удобства.
"""

from __future__ import annotations

import pathlib

__all__ = [
    "SOLUTION_NAME",
    "TASK_TEMPLATE",
    "TEST_EXPECTED",
    "TEST_INPUT",
    "create_task_dir",
]

#: Имя решения. `task<N>_<M>.py` — приоритетный шаблон поиска: пока такой файл
#: лежит рядом, соседний `utils.py` в проверку не попадёт.
SOLUTION_NAME = "task1_1.py"

#: Вход и ожидаемый вывод теста №1 — Legacy-раскладка (`N`, `N.clue`).
TEST_INPUT = "2 3\n"
TEST_EXPECTED = "5\n"

#: Минимальное решение, которое действительно проходит созданный тест.
TASK_TEMPLATE = """\
# Решение задачи. Вход читается со stdin, ответ печатается в stdout.
#
# Тест №1 лежит в tests/1 (вход) и tests/1.clue (ожидаемый вывод).
# Своих тестов можно добавить сколько угодно: 2 и 2.clue, 3 и 3.clue, …
#
# Если задача function-style (проверяется вызов функции, а не stdin),
# положите рядом meta.json с одной строкой: {"function_name": "solve"}
a, b = map(int, input().split())
print(a + b)
"""


def create_task_dir(path: pathlib.Path) -> pathlib.Path:
    """Создать каталог задачи по открытому контракту.

    Args:
        path: каталог, который нужно создать.

    Returns:
        Путь созданного файла решения — им же пользуются в подсказке
        «следующий шаг».

    Raises:
        FileExistsError: каталог уже существует. Чужая работа не перезатирается
            молча; решение — за человеком.
    """
    if path.exists():
        raise FileExistsError(str(path))

    tests = path / "tests"
    tests.mkdir(parents=True)
    solution = path / SOLUTION_NAME
    solution.write_text(TASK_TEMPLATE, encoding="utf-8")
    (tests / "1").write_text(TEST_INPUT, encoding="utf-8")
    (tests / "1.clue").write_text(TEST_EXPECTED, encoding="utf-8")
    return solution
