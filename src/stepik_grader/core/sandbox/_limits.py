"""_limits.py — значения лимитов изоляции, общие для трёх backend'ов.

Отдельный модуль без зависимостей намеренно: ``sandbox/__init__.py`` импортирует
backend'ы лениво (внутри функции), поэтому обратный импорт константы из пакета
на уровне модуля backend'а замкнул бы цикл.
"""

from __future__ import annotations

import math

__all__ = [
    "SANDBOX_FALLBACK_MEMORY_MB",
    "cpu_quota_seconds",
    "sandbox_memory_mb",
]

# issue #986: запас поверх wall-таймаута. Часы и CPU-время расходятся: решение,
# жгущее CPU в несколько потоков, тратит процессорных секунд больше, чем прошло
# по часам.
_CPU_QUOTA_SLACK_SECONDS = 1


def cpu_quota_seconds(timeout: float, configured_max: float) -> int:
    """CPU-квота изоляции для прогона с wall-таймаутом ``timeout`` (issue #986).

    Квота обязана быть backstop'ом **под** таймаутом, а не жёстче него: иначе
    изоляция убивает верное решение раньше, чем истекло разрешённое ему время.
    Берётся максимум из «таймаут + запас» и настроенного потолка — настройка
    остаётся нижней границей (защищает, когда таймаут крошечный), а длинный
    прогон получает квоту не меньше своего таймаута.

    Живёт здесь, а не в ``_posix_bootstrap`` (issue #927): формула чисто
    арифметическая и нужна всем трём backend'ам, но Windows-backend POSIX-модуль
    импортировать не может. Пока она лежала на POSIX-стороне, Windows считал
    квоту от одной константы — и `--timeout 60` там не работал вовсе.
    """
    from_timeout = math.ceil(timeout) + _CPU_QUOTA_SLACK_SECONDS
    return max(1, from_timeout, math.ceil(configured_max))


# issue #986 (CANON-2-02): потолок памяти, когда его не задали нигде.
#
# ``docs/use/configuration.md`` описывает ``max_memory_mb = None`` как «без
# лимита», и для обычного прогона (``LocalRunner``) это правда. Под изоляцией —
# нет и не должно быть: песочница без потолка памяти не изолирует, а
# сопровождает решение до OOM всей машины. Значение подставлялось молча четырьмя
# копиями литерала `1024`, поэтому расхождение с документом выглядело как
# оплошность, а не как решение. Теперь у него есть имя и объяснение, а документ
# говорит то же самое.
SANDBOX_FALLBACK_MEMORY_MB = 1024


def sandbox_memory_mb(spec_value: int | None, configured: int | None) -> int:
    """Потолок памяти для прогона под изоляцией (issue #986).

    Порядок: явное значение запроса → настройка грейдера → запасной потолок
    изоляции. ``None`` на всех трёх уровнях означает не «без лимита», а
    ``SANDBOX_FALLBACK_MEMORY_MB``: см. комментарий к константе.
    """
    return spec_value or configured or SANDBOX_FALLBACK_MEMORY_MB
