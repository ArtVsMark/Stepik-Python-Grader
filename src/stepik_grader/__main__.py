"""Точка входа для `python -m stepik_grader` (issue #65).

Делегирует в ту же `cli.main()`, что и консольная команда `stepik-grader`
и `python -m stepik_grader.grader`.
"""

from __future__ import annotations

import pathlib
import sys


def _drop_cwd_from_path() -> None:
    """Убрать текущий каталог из ``sys.path`` (issue #996, ``INS-3-01``).

    ``python -m`` кладёт cwd **первым** в ``sys.path``, а грейдер запускают из
    каталога задачи — где лежит решение студента. Файл с именем stdlib-модуля
    (``json.py``, ``string.py``, ``random.py``, ``logging.py`` — обычные имена
    для учебной задачи) перекрывал настоящий модуль, и грейдер падал
    трейсбеком в свои же внутренности, ещё не показав ни одного экрана.

    Из cwd нам не нужно ничего: пакет ставится через ``pip install -e .``, и
    решение пользователя исполняется в отдельном процессе — обёртка сама
    добавляет нужный каталог в путь ребёнка (``wrapper_builder``).

    **Чинит не все случаи, и это предел приёма, а не недоделка.** Модули,
    которые нужны самому ``runpy`` (``types``, ``importlib``), загружаются
    ДО первой строки этого файла: там интерпретатор печатает «Could not import
    runpy module» и до нас управление не доходит вовсе. Работает всё, что
    тянется уже нашим кодом.
    """
    cwd = str(pathlib.Path.cwd())
    sys.path[:] = [entry for entry in sys.path if entry not in ("", ".", cwd)]


if __name__ == "__main__":
    _drop_cwd_from_path()

    # Импорт — ПОСЛЕ чистки пути: он и тянет за собой stdlib-модули, которые
    # файл-однофамилец перекрывает. Верхнеуровневый импорт свёл бы фикс на нет.
    from stepik_grader.cli import run_cli

    # issue #936: код исхода прогона становится статусом процесса.
    run_cli()
