#!/usr/bin/env python3
"""Стартовый хук окна: правила проекта читаются ДО первой правки (issue #1384).

Второй рубеж. Первый — механизм: гейт краснеет, и правило действует независимо
от памяти окна. Но механизмом покрыто не всё, а непокрытое держится тем, что
окно про правило знает, — то есть тем, что оно прочитало. `CLAUDE.md`
формулирует немногие правила, указатель перечисляет заголовки, а сами
утверждения живут в каталоге, куда в работе никто не заходит.

Хук печатает дайджест (`docs/agent/rules/DIGEST.md`) в стартовый контекст. Вывод
хука `SessionStart` попадает окну как обычный текст, поэтому дайджест
оказывается прочитанным раньше, чем окно успеет что-нибудь нарушить.

Три свойства, без которых это было бы вредно:

1. **Ничего не устанавливает и никуда не ходит.** Только чтение локального
   файла: стартовый хук на сетевом вызове превращает открытие окна в лотерею.
2. **Отсутствие дайджеста — не отказ.** Печатается строка о том, что файла нет
   и чем это чинится; ронять старт сессии из-за документа нельзя.
3. **Свежесть — не его забота.** За отставание дайджеста от каталога отвечает
   `scripts/check_rules_digest.py`: хук обязан быть быстрым и безусловным.
"""

from __future__ import annotations

import os
import pathlib
import sys

_HERE = pathlib.Path(__file__).resolve().parent
_DEFAULT_ROOT = _HERE.parent.parent
_RELATIVE = pathlib.Path("docs") / "agent" / "rules" / "DIGEST.md"

_HEADER = """\
# Правила проекта — прочитать до первой правки

Ниже утверждения всех правил, действующих в этом проекте, одной строкой каждое.
Сначала идут те, которые НЕ поймает ни один гейт: если окно про них забудет, не
заметит никто. Полный текст правила — в каталоге Engineering-Incidents-Playbook,
`rules/ru/<номер>-*.md`; чем правило держится здесь — `.rules/bindings.json`.
"""


def _force_utf8_stdio() -> None:
    """Печатать UTF-8 независимо от кодовой страницы консоли (issue #1108).

    Дайджест русский, и в консоли cp1251 (русская Windows, а также раннеры CI
    с узкой кодовой страницей) ``print`` падал бы ``UnicodeEncodeError`` — то
    есть хук ронял бы старт сессии из-за кодировки. Поймано прогоном: на всех
    трёх Windows-комбинациях матрицы хук возвращал код 1.

    Собственная копия приёма, а не импорт из пакета: хук обязан работать там,
    где пакет не установлен. No-op на потоках без ``reconfigure``.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="replace")


def main() -> int:
    """Напечатать дайджест правил; отсутствие файла — сообщение, а не отказ."""
    # Раньше любой печати: сообщение об отсутствии дайджеста тоже русское.
    _force_utf8_stdio()
    # Хук читает stdin по контракту площадки; содержимое нам не нужно, но
    # не прочитать его значит оставить пишущей стороне сломанный канал.
    if not sys.stdin.isatty():
        sys.stdin.read()

    root = pathlib.Path(os.environ.get("CLAUDE_PROJECT_DIR", _DEFAULT_ROOT))
    digest = root / _RELATIVE
    try:
        text = digest.read_text(encoding="utf-8")
    except OSError as exc:
        print(
            f"Дайджест правил не прочитан ({exc}). Правила действуют всё равно: "
            "смотрите CLAUDE.md и .rules/bindings.json, а файл пересоберите — "
            "python scripts/generate_rules_digest.py --catalogue <клон каталога>."
        )
        return 0

    # Служебная шапка самого файла окну не нужна: она объясняет, как файл
    # собран, а не что делать.
    body = "\n".join(line for line in text.splitlines() if not line.startswith("<!--"))
    print(_HEADER)
    print(body.strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
