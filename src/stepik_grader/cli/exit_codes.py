"""exit_codes.py — коды возврата CLI как машинный контракт.

Архитектурный слой: Interface / CLI.

issue #936: `--mode 1/2` документированы как CI-сценарий, а `--output json/csv`
описан в справке словами «для CI-пайплайнов» — при этом код возврата всегда был
``0``. Гейт, построенный по этой рекомендации, зеленел и на проваленных кейсах,
и на пустом наборе тестов: узнать исход можно было только разбором JSON.

Значения выбраны так, чтобы истинностная семантика совпадала с прежним
``had_failures``: ``OK`` ложно, всё остальное истинно. Меню при этом различает
исходы явно — «тестов не нашлось» не должно ни печатать подсказку «Подучить»,
ни сбрасывать серию зачётов: прогона не было.
"""

from __future__ import annotations

import enum

__all__ = ["ExitCode"]


class ExitCode(enum.IntEnum):
    """Код возврата прогона: ``0`` — всё сошлось, ``1`` — упало, ``2`` — нечего проверять."""

    OK = 0
    FAILURES = 1
    NO_TESTS = 2
